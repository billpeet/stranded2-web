// PORTING_GUIDE.md: the generated sections
// =====================================================================================

function genGuide(index, moduleKinds) {
	const file = join(OUT, 'PORTING_GUIDE.md');
	if (!existsSync(file)) return;
	let md = readFileSync(file, 'utf8');
	const put = (name, body) => {
		const a = `<!-- GENERATED:${name} BEGIN -->`;
		const b = `<!-- GENERATED:${name} END -->`;
		const i = md.indexOf(a);
		const j = md.indexOf(b);
		if (i < 0 || j < 0) throw new Error('PORTING_GUIDE.md: marker ' + name + ' missing');
		md = md.slice(0, i + a.length) + '\n' + body.trimEnd() + '\n' + md.slice(j);
	};
	const fns = index.functions;
	const KIND_TEXT = { own: 'own', facade: 'facade', partial: 'partial', skeleton: 'skeleton', declarations: 'declarations', dead: 'dead' };

	// ---- file map
	let fm = '| original file | lines | module | kind | functions (ported / to port) | notes |\n| --- | --- | --- | --- | --- | --- |\n';
	for (const f of P.files) {
		const sf = shortFile(f);
		const info = index.files[sf];
		const list = fns.filter((e) => e.file === sf && !e.toplevel);
		const ported = list.filter((e) => e.status === 'ported').length;
		const todo = list.filter((e) => e.status === 'todo');
		const inc = fns.find((e) => e.file === sf && e.toplevel);
		const notes = [];
		if (DEAD_FILES[f]) notes.push(DEAD_FILES[f]);
		if (f === 'StrandedII.bb') notes.push('startup(), mainLoopStep(), main()');
		if (info.kind === 'declarations') notes.push(f.includes('const') ? 'constants: consts.ts' : f.endsWith('udp.bb') ? 'only Includes the udp_*.bb files' : 'globals and arrays: state.ts (G); types: types.ts');
		if (inc) notes.push(`top-level code: \`${inc.name}()\` ${inc.status === 'absorbed' ? '- ' + inc.note : inc.status === 'ported' ? '(exists)' : '(to port)'}`);
		const via = [...new Set(list.filter((e) => e.status === 'ported').map((e) => e.via.replace(/\.\w+\(\)$/, '')))];
		if (via.length && info.kind !== 'own') notes.push('exists in ' + via.join(', '));
		if (info.kind === 'partial') notes.push('to port: ' + todo.map((e) => e.name).join(', '));
		const absorbed = list.filter((e) => e.status === 'absorbed');
		if (absorbed.length) notes.push('no function in the port: ' + absorbed.map((e) => e.name).join(', '));
		const pkg = PACKAGES.find((p) => p.files.includes(baseOf(f)));
		if (pkg) notes.push('package **' + pkg.id + '**');
		fm += `| ${sf} | ${info.lines} | ${info.module ? '\`' + info.module.replace('$lib/s2/', '') + '\`' : '-'} | ${KIND_TEXT[info.kind]} | ${list.length ? ported + ' / ' + todo.length : '-'} | ${notes.join('; ').replaceAll('|', '\\|')} |\n`;
	}
	put('FILEMAP', fm);

	// ---- barriers
	const barriers = fns.filter((e) => e.barrier);
	put('BARRIERS', barriers.map((e) => `- \`${e.name}\` (${e.file}): ${e.barrier}`).join('\n'));

	// ---- async list
	const as = fns.filter((e) => e.async);
	let al = `${as.length} functions are async (${as.filter((e) => e.status === 'todo').length} of them still to port). Everything else is synchronous.\n\n`;
	al += '| function | file | status | why |\n| --- | --- | --- | --- |\n';
	for (const e of as) al += `| \`${e.export}\` | ${e.file} | ${e.status} | ${e.status === 'ported' ? 'async in the port (' + e.via + ')' : e.asyncBecause} |\n`;
	put('ASYNC', al);

	// ---- packages
	const assigned = new Map();
	for (const p of PACKAGES) for (const b of p.files) {
		if (assigned.has(b)) throw new Error(`file ${b} is in two packages`);
		assigned.set(b, p.id);
	}
	const todoFiles = new Set(fns.filter((e) => e.status === 'todo').map((e) => e.module.replace('$lib/s2/game/', '')));
	for (const b of todoFiles) if (!assigned.has(b)) throw new Error(`file ${b} has functions to port but no package`);
	const hostCount = (mod) => (read(`script/commands/${mod}.ts`).match(/\(P: ParseCtx/g) ?? []).length;
	let pk = 'Each package is one unit of ownership (section 4). Lines are those of the original files; "to port" counts functions and `include_` bodies.\n\n';
	pk += '| package | subject | files (lines) | lines | to port | async | ScriptHost methods |\n| --- | --- | --- | --- | --- | --- | --- |\n';
	const summary = [];
	for (const p of PACKAGES) {
		let lines = 0;
		let todo = 0;
		let asyncN = 0;
		const parts = [];
		for (const b of p.files) {
			const sf = (b.includes('/') ? b : b) + '.bb';
			const list = fns.filter((e) => e.file === sf && e.status === 'todo');
			// only the part of a partially ported file that is left counts
			const kind = index.files[sf].kind;
			const l = kind === 'partial' ? list.reduce((n, e) => n + e.lines, 0) : index.files[sf].lines;
			lines += l;
			todo += list.length;
			asyncN += list.filter((e) => e.async).length;
			parts.push(`${b} (${l}${kind === 'partial' ? ' of ' + index.files[sf].lines : ''})`);
		}
		const host = (p.host ?? []).reduce((n, m) => n + hostCount(m), 0);
		const fileText = p.files.length > 12 ? `${p.files.slice(0, 3).join(', ')}, ai/*.bb (21 files)` : parts.join(', ');
		pk += `| **${p.id}** | ${p.title} | ${p.files.length ? fileText : '-'} | ${lines || '-'} | ${todo || '-'} | ${asyncN || '-'} | ${host ? host + ' (script_host/' + p.id + '.ts: commands/' + p.host.join(', ') + ')' : 'its own subject, as needed by script1/script2'} |\n`;
		summary.push({ id: p.id, lines, todo, asyncN, host });
	}
	pk += '\nNotes\n\n' + PACKAGES.map((p) => `- **${p.id}**: ${p.notes}`).join('\n') + '\n';
	pk += '\nThe ScriptHost methods (section 11) are written by script1 and script2 as thin calls into the functions of the other packages; a package may take over the methods of its own subject by putting them into its own `script_host/<package>.ts` and telling script1/script2 (a method must exist only once).\n';
	pk += '\nSuggested order when not everything runs in parallel: entities1, entities2, map, menu (the game then loads and shows a map), player, combat, interface, ai, script1, script2, editor, net.\n';
	put('PACKAGES', pk);

	write('PORTING_GUIDE.md', md);
	return summary;
}

