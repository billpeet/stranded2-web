const constEnv = new Map();
for (const c of P.consts) {
	const v = evalExpr(c.value, c.type);
	if (v !== undefined) constEnv.set(c.name.toLowerCase(), v);
}
function evalExpr(expr, type) {
	if (expr == null) return undefined;
	let e = expr.trim();
	if (/^"[^"]*"$/.test(e)) return e.slice(1, -1);
	e = e.replace(/[#%$]/g, '');
	if (/^[-+]?(\d+\.?\d*|\.\d+)$/.test(e)) return Number(e);
	// identifiers and + - * between numbers
	const toks = e.match(/[A-Za-z_]\w*|\d+\.?\d*|[-+*()]/g);
	if (!toks || toks.join('') !== e.replace(/\s+/g, '')) return undefined;
	let js = '';
	for (const t of toks) {
		if (/^[A-Za-z_]/.test(t)) {
			const v = constEnv.get(t.toLowerCase());
			if (typeof v !== 'number') return undefined;
			js += `(${v})`;
		} else js += t;
	}
	try {
		const v = Function(`"use strict";return (${js});`)();
		return typeof v === 'number' && Number.isFinite(v) ? (type === 'float' ? v : Math.trunc(v)) : undefined;
	} catch {
		return undefined;
	}
}
