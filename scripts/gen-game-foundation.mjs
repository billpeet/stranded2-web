function write(rel, text, { skeleton = false } = {}) {
	const file = join(OUT, rel);
	const old = existsSync(file) ? readFileSync(file, 'utf8') : null;
	// a skeleton is only ever created: an existing file is either ported or being ported by its owner
	if (skeleton && old !== null) return false;
	if (old === text) return false;
	if (CHECK) {
		stale++;
		console.log('out of date: ' + rel);
		return false;
	}
	mkdirSync(dirname(file), { recursive: true });
	writeFileSync(file, text);
	return true;
}
