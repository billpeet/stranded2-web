function paramTs(fn, p) {
	const key = p.name.toLowerCase();
	for (const [ts, byName] of Object.entries(PARAM_HANDLE)) {
		if (byName[key]?.includes(fn.name.toLowerCase())) return ts;
	}
	if (p.type === 'ref') return `${refClass(p.ref)} | null`;
	return sigilTs(p.type);
}
const RESERVED = new Set(['class', 'in', 'default', 'new', 'delete', 'function', 'var', 'case', 'switch', 'for', 'if', 'else', 'do', 'while', 'this', 'typeof', 'void', 'with', 'enum', 'export', 'import', 'return', 'try', 'catch', 'throw', 'const', 'let', 'static', 'super', 'null', 'true', 'false', 'break', 'continue', 'debugger', 'finally', 'instanceof', 'yield', 'await', 'package', 'interface', 'private', 'public', 'protected', 'implements', 'arguments', 'eval']);
const paramName = (n) => (RESERVED.has(n) ? n + '_' : n);
/** A function whose name is a reserved word of JavaScript is exported with a trailing underscore (interface -> interface_). */
const exportName = (n) => (RESERVED.has(n) ? n + '_' : n);

function defaultTs(p, ts) {
	if (p.default === null) return null;
	const v = evalExpr(p.default, p.type);
	if (v !== undefined) {
		if (ts === 'Handle' || ts.endsWith('| null')) return v === 0 ? 'null' : null;
		return tsLit(v, p.type);
	}
	return null;
}

/** False for a function that never returns a value (only `Return` or nothing): it is `void` in the port. */
function returnsValue(fn) {
	for (const { code } of fn.body) {
		for (const stmt of code.split(':')) {
			for (const part of stmt.split(/\b(?:Then|Else)\b/i)) {
				const m = /^\s*Return\b(.*)$/i.exec(part);
				if (m && m[1].trim() !== '') return true;
			}
		}
	}
	return false;
}

function tsSignature(fn, isAsync) {
	// Blitz allows a parameter without default after one with a default; TypeScript too, but only the trailing ones are optional.
	const ps = fn.params.map((p) => {
		const ts = paramTs(fn, p);
		const def = defaultTs(p, ts);
		const name = paramName(p.name);
		if (def !== null) return `${name}: ${ts} = ${def}`;
		if (p.default !== null) return `${name}: ${ts} /* = ${p.default} */`;
		return `${name}: ${ts}`;
	});
	let ret = RETURN_T[fn.name.toLowerCase()] ?? (fn.ret === 'ref' ? `${refClass(fn.retRef)} | null` : fn.ret === 'int' && !returnsValue(fn) ? 'void' : sigilTs(fn.ret));
	if (isAsync) ret = `Promise<${ret}>`;
	return { params: ps.join(', '), ret };
}

function bbSignature(fn) {
	const sig = { int: '', float: '#', string: '$' };
	const ps = fn.params.map((p) => p.name + (p.type === 'ref' ? '.' + p.ref : sig[p.type]) + (p.default !== null ? '=' + p.default : ''));
	return `${fn.name}${fn.ret === 'ref' ? '.' + fn.retRef : sig[fn.ret]}(${ps.join(',')})`;
}

function detectAsync(spec, name) {
	if (spec.async !== undefined) return spec.async;
	if (spec.kind === 'reexport') {
		const rel = spec.from.replace('../', '');
		const candidates = [rel + '.ts', rel + '/index.ts', rel === 'blitz' ? 'blitz/functions.ts' : null].filter(Boolean);
		for (const c of candidates) {
			if (!existsSync(join(LIB, c))) continue;
			const src = read(c);
			const m = new RegExp(`^export (async )?function ${spec.as ?? name}\\b`, 'm').exec(src);
			if (m) return !!m[1];
		}
		throw new Error(`cannot find export ${name} in ${spec.from}`);
	}
	if (spec.kind === 'method') {
		const src = read(METHOD_OBJ[spec.obj].src);
		const m = new RegExp(`^\\t(async )?${name}\\(`, 'm').exec(src);
		if (!m) throw new Error(`cannot find method ${name} in ${METHOD_OBJ[spec.obj].src}`);
		return !!m[1];
	}
	return false;
}

/** The source of game/<base>.ts when its owner has ported it (the file exists and is no skeleton), else null. */
const landedCache = new Map();
function landedSource(base) {
	if (!landedCache.has(base)) {
		const file = join(OUT, base + '.ts');
		const src = existsSync(file) ? readFileSync(file, 'utf8') : null;
		landedCache.set(base, src !== null && !src.startsWith('// @skeleton') ? src : null);
	}
	return landedCache.get(base);
}
/** The real signature of `export [async] function name(...)` in a ported module: { async, params, ret } or null. */
function landedSignature(src, name) {
	const m = new RegExp(`^export (async )?function ${name}\\s*\\(`, 'm').exec(src);
	if (!m) return null;
	let i = m.index + m[0].length;
	let depth = 1;
	const start = i;
	for (; i < src.length && depth > 0; i++) {
		const ch = src[i];
		if (ch === '(') depth++;
		else if (ch === ')') depth--;
	}
	const params = src.slice(start, i - 1).replace(/\s+/g, ' ').trim();
	const rest = src.slice(i);
	const r = /^\s*:\s*([^{]+?)\s*\{/.exec(rest);
	const isAsync = !!m[1];
	return { async: isAsync, params, ret: r ? r[1].trim() : isAsync ? 'Promise<void>' : 'void' };
}

function genFunctions() {
	const entries = [];
	const seenFn = new Set();
	for (const fn of P.functions) {
		const dead = DEAD_FILES[fn.file];
		const key = fn.name.toLowerCase();
		const e = {
			name: fn.name.toLowerCase(),
			bb: bbSignature(fn),
			file: shortFile(fn.file),
			line: fn.line,
			lines: fn.endLine - fn.line + 1,
			module: `$lib/s2/game/${baseOf(fn.file)}`,
			export: exportName(fn.name.toLowerCase()),
			async: false,
			status: 'todo',
			calls: fn.calls.map((c) => c.toLowerCase())
		};
		if (dead) {
			e.status = 'dead';
			e.module = '';
			e.note = dead;
			entries.push({ e, fn });
			continue;
		}
		if (seenFn.has(key)) throw new Error('duplicate function ' + fn.name);
		seenFn.add(key);
		const spec = EXISTING[key];
		if (spec) {
			if (spec.kind === 'absorbed') {
				e.status = 'absorbed';
				e.module = '';
				e.note = spec.where;
			} else {
				e.status = 'ported';
				e.async = detectAsync(spec, e.name);
				e.via = spec.kind === 'reexport' ? spec.from.replace('../', 'src/lib/s2/') : spec.kind === 'method' ? `${METHOD_OBJ[spec.obj].expr}.${e.name}()` : `game/${spec.mod}.ts`;
			}
		}
		entries.push({ e, fn, spec });
	}
	// functions that only exist in the shipped executable
	for (const x of EXE_ONLY) {
		entries.push({
			e: { name: x.name, bb: `${x.name}(...)`, file: shortFile(x.file), line: 0, lines: 0, module: `$lib/s2/game/${baseOf(x.file)}`, export: x.name, async: false, status: 'todo', calls: [], note: `not in the repository source: port from ../s2_re/out/decomp/${x.decomp}` },
			fn: null,
			exe: x
		});
	}
	// top-level code
	const includes = [];
	for (const file of P.files) {
		if (file === 'StrandedII.bb' || DEAD_FILES[file]) continue;
		const top = P.toplevel[file];
		const owner = INCLUDE_OWNER[file];
		if (!top.length && !owner) continue;
		const name = `include_${baseOf(file).replace(/^ai\//, '')}`;
		const e = { name, bb: '(top-level code)', file: shortFile(file), line: top[0]?.line ?? 0, lines: top.length, module: `$lib/s2/game/${baseOf(file)}`, export: name, async: false, status: 'todo', calls: P.topCalls[file].calls.map((c) => c.toLowerCase()), toplevel: true };
		if (owner?.kind === 'absorbed') {
			e.status = 'absorbed';
			e.module = '';
			e.note = owner.where;
		} else if (owner) {
			e.status = 'ported';
			e.async = !!owner.async;
			e.via = `game/${owner.mod}.ts`;
		}
		if (file.startsWith('includes/ai/')) e.note = 'included inside the Select of update_unit (ai_units.bb): a function called from there';
		includes.push({ e, file, owner, blocks: P.topCalls[file].blocks });
	}

	// ---- modules that have landed: a ported module is the truth for status, sync/async and signature
	for (const x of [...entries, ...includes]) {
		if (x.e.status !== 'todo') continue;
		const base = x.e.module.replace('$lib/s2/game/', '');
		const src = landedSource(base);
		if (src === null) continue;
		const sig = landedSignature(src, x.e.export);
		if (!sig) throw new Error(`${base}.ts is ported but does not export function ${x.e.export}`);
		x.e.status = 'ported';
		x.e.async = sig.async;
		x.e.via = `game/${base}.ts`;
		x.landed = sig;
		x.spec = OWN(base);
		if (x.exe) x.e.note = `not in the repository source: ported from ../s2_re/out/decomp/${x.exe.decomp}`;
	}

	// ---- sync/async of everything still to port
	const byName = new Map();
	for (const x of entries) if (x.e.status !== 'dead') byName.set(x.e.name, x);
	for (const x of includes) byName.set(x.e.name, x);
	const reason = new Map();
	for (const x of byName.values()) if (x.e.status === 'ported' && x.e.async) reason.set(x.e.name, 'async in the port');
	let changed = true;
	const todo = [...byName.values()].filter((x) => x.e.status === 'todo');
	for (const x of todo) {
		const blocks = x.fn ? x.fn.blocks : (x.blocks ?? []);
		if (blocks.length && !SYNC_BARRIERS[x.e.name]) reason.set(x.e.name, blocks.map((b) => b[0].toUpperCase() + b.slice(1)).join('/'));
	}
	while (changed) {
		changed = false;
		for (const x of todo) {
			if (reason.has(x.e.name) || SYNC_BARRIERS[x.e.name]) continue;
			const c = x.e.calls.find((n) => reason.has(n));
			if (c) {
				reason.set(x.e.name, 'calls ' + c);
				changed = true;
			}
		}
	}
	for (const x of todo) {
		if (reason.has(x.e.name)) {
			x.e.async = true;
			x.e.asyncBecause = reason.get(x.e.name);
		} else if (SYNC_BARRIERS[x.e.name]) {
			const c = x.e.calls.filter((n) => reason.has(n));
			if (c.length || (x.fn && x.fn.blocks.length)) x.e.barrier = `${SYNC_BARRIERS[x.e.name]}; defers: ${c.join(', ') || 'its own wait'}`;
		}
	}
	// ported sync functions whose original calls something async: barriers as well
	for (const x of byName.values()) {
		if (x.e.status !== 'ported' || x.e.async) continue;
		const c = x.e.calls.filter((n) => reason.has(n));
		if (c.length) x.e.barrier = `${SYNC_BARRIERS[x.e.name] ?? 'synchronous in the port'}; reaches async: ${c.join(', ')}`;
	}

	// ---- TypeScript signatures
	for (const x of [...entries, ...includes]) {
		if (x.landed) x.e.ts = `${x.landed.async ? 'async ' : ''}${x.e.export}(${x.landed.params}): ${x.landed.ret}`;
	}
	for (const x of entries) {
		if (x.landed) continue;
		if (x.fn) {
			const s = tsSignature(x.fn, x.e.async);
			x.e.ts = `${x.e.async ? 'async ' : ''}${x.e.export}(${s.params}): ${s.ret}`;
			x.sig = s;
		} else if (x.exe) x.e.ts = `${x.e.name}${x.exe.ts}`;
	}
	for (const x of includes) if (!x.landed) x.e.ts = `${x.e.async ? 'async ' : ''}${x.e.name}(): ${x.e.async ? 'Promise<void>' : 'void'}`;

	// ---- modules
	const byFile = new Map();
	for (const x of [...entries, ...includes]) {
		if (x.e.status === 'dead' || x.e.status === 'absorbed') continue;
		const file = x.fn ? x.fn.file : (x.file ?? x.exe.file);
		if (!byFile.has(file)) byFile.set(file, []);
		byFile.get(file).push(x);
	}
	const moduleKinds = {};
	for (const [file, list] of byFile) {
		const base = baseOf(file);
		const depth = base.includes('/') ? '../' : './';
		const up = base.includes('/') ? '../../' : '../';
		const ported = list.filter((x) => x.e.status === 'ported');
		const todoList = list.filter((x) => x.e.status === 'todo');
		const specOf = (x) => x.spec ?? x.owner;
		if (landedSource(base) !== null && list.some((x) => x.landed)) {
			// ported by its owner (it re-exports <base>.ported.ts itself where one exists): nothing to generate
			if (todoList.length) throw new Error(`${file}: ${base}.ts is ported but lacks ${todoList.map((x) => x.e.name).join(', ')}`);
			moduleKinds[file] = 'own';
			continue;
		}
		// functions I provide in a hand-written module with the file's own name: nothing to generate
		const ownHere = ported.filter((x) => specOf(x).kind === 'own' && specOf(x).mod === base);
		const elsewhere = ported.filter((x) => !(specOf(x).kind === 'own' && specOf(x).mod === base));

		let facade = '';
		if (elsewhere.length) {
			const groups = new Map();
			let methods = '';
			const needRT = new Set();
			for (const x of elsewhere) {
				const spec = specOf(x);
				if (spec.kind === 'reexport') {
					const from = spec.from.replace('../', up);
					if (!groups.has(from)) groups.set(from, []);
					groups.get(from).push(spec.as ? `${spec.as} as ${x.e.name}` : x.e.name);
				} else if (spec.kind === 'own') {
					const from = `${depth}${spec.mod}`;
					if (!groups.has(from)) groups.set(from, []);
					groups.get(from).push(x.e.name);
				} else if (spec.kind === 'method') {
					const o = METHOD_OBJ[spec.obj];
					needRT.add(spec.obj);
					methods += `/** ${x.e.bb} (${x.e.file}:${x.e.line}) */\nexport function ${x.e.name}(...a: Parameters<${o.type}['${x.e.name}']>): ReturnType<${o.type}['${x.e.name}']> {\n\treturn ${o.expr}.${x.e.name}(...a);\n}\n\n`;
				}
			}
			facade += HEADER;
			facade += `/**\n * ${shortFile(file)}: the functions of this file that already exist in a runtime layer,\n * under their original names. ${[...needRT].length ? 'Method facades call the session object in RT (rt.ts).' : ''}\n */\n`;
			for (const obj of needRT) facade += `import type { ${METHOD_OBJ[obj].type} } from '${METHOD_OBJ[obj].from.replace('../', up)}';\n`;
			if (needRT.size) facade += `import { RT } from '${depth}rt';\n`;
			if (needRT.size) facade += '\n';
			for (const [from, names] of groups) facade += `export { ${names.join(', ')} } from '${from}';\n`;
			if (methods) facade += '\n' + methods.trimEnd() + '\n';
		}

		if (!todoList.length) {
			if (ownHere.length && elsewhere.length) throw new Error(`${file}: mixes own-module and facade functions`);
			if (elsewhere.length) {
				write(`${base}.ts`, facade);
				moduleKinds[file] = 'facade';
			} else moduleKinds[file] = 'own';
			continue;
		}
		if (ownHere.length) throw new Error(`${file}: hand-written module ${base}.ts cannot also have functions to port`);
		const hasPorted = elsewhere.length > 0;
		const handPorted = elsewhere.length > 0 && elsewhere.every((x) => specOf(x).kind === 'own' && specOf(x).mod === `${base}.ported`);
		if (hasPorted && !handPorted) {
			// keep hand-written .ported exports: re-export them from the generated facade is not possible, so forbid mixing
			if (elsewhere.some((x) => specOf(x).kind === 'own' && specOf(x).mod === `${base}.ported`)) {
				// mixed: the hand-written <base>.ported.ts must itself re-export the layer functions
				const need = elsewhere.filter((x) => !(specOf(x).kind === 'own' && specOf(x).mod === `${base}.ported`)).map((x) => x.e.name);
				const src = existsSync(join(OUT, `${base}.ported.ts`)) ? readFileSync(join(OUT, `${base}.ported.ts`), 'utf8') : '';
				for (const n of need) if (!new RegExp(`\\b${n}\\b`).test(src)) console.warn(`WARNING ${base}.ported.ts must re-export ${n}`);
			} else write(`${base}.ported.ts`, facade);
		}
		moduleKinds[file] = hasPorted ? 'partial' : 'skeleton';

		// ---- skeleton
		let sk = `// @skeleton  (remove this line when you port the file; see PORTING_GUIDE.md)\n`;
		sk += `/**\n * ${shortFile(file)} - NOT PORTED YET. Generated signatures so that imports resolve and type-check while\n * the modules are ported in parallel. The owner of this file replaces every body (and this header) with\n * the line-by-line port; names, parameter order, defaults and sync/async are the contract.\n */\n`;
		const imports = new Set();
		let fns = '';
		const names = [];
		for (const x of todoList) {
			names.push(x.e.export);
			let params = '';
			let ret = 'void';
			if (x.fn) {
				params = x.sig.params;
				ret = x.sig.ret;
				for (const t of [...params.matchAll(/\b(T[A-Za-z0-9_]+) \| null/g)].map((m) => m[1])) if (t !== 'Texture') imports.add(t);
				const rt = /^(?:Promise<)?(T[A-Za-z0-9_]+) \| null/.exec(ret);
				if (rt && rt[1] !== 'Texture') imports.add(rt[1]);
			} else if (x.exe) {
				params = '...args: number[]';
				ret = 'number';
			} else ret = x.e.async ? 'Promise<void>' : 'void';
			const loc = x.fn ? `${x.e.bb}  (${x.e.file}:${x.e.line}, ${x.e.lines} lines)` : x.exe ? `${x.e.name}: only in the executable, see ${x.exe.decomp}` : `top-level code of ${x.e.file} (${x.e.lines} statements)`;
			const more = [x.e.asyncBecause ? `async: ${x.e.asyncBecause}` : '', x.e.barrier ? `sync barrier: ${x.e.barrier}` : '', x.e.note ?? ''].filter(Boolean).join('; ');
			fns += `/** ${doc(loc)}${more ? `\n * ${doc(more)}` : ''} */\n`;
			fns += `export ${x.e.async ? 'async ' : ''}function ${x.e.export}(${params.replace(/(\w+): /g, '_$1: ')}): ${ret} {\n\treturn notPorted('${x.e.name}');\n}\n\n`;
		}
		const useHandle = /: Handle\b|Handle>/.test(fns);
		const useImage = /ImageHandle/.test(fns);
		const useTexture = /Texture \| null/.test(fns);
		if (useHandle || useTexture) sk += `import type { ${[useHandle ? 'Handle' : '', useTexture ? 'Texture' : ''].filter(Boolean).join(', ')} } from '${up}bb3d';\n`;
		if (useImage) sk += `import type { ImageHandle } from '${up}gfx2d';\n`;
		sk += `import { markSkeleton, notPorted } from '${depth}_stubs';\n`;
		if (imports.size) sk += `import type { ${[...imports].sort().join(', ')} } from '${depth}types';\n`;
		sk += '\n';
		if (hasPorted) sk += `export * from './${base.split('/').pop()}.ported';\n\n`;
		sk += fns;
		sk += `markSkeleton(${names.join(', ')});\n`;
		write(`${base}.ts`, sk, { skeleton: true });
	}

	// ---- index files
	const all = [...entries, ...includes].map((x) => x.e);
	const index = {
		generated: 'scripts/gen-game-foundation.mjs',
		note: 'Every Function of the original source and the top-level code of every included file. module/export: where to import it from. status: ported (exists now) | todo | absorbed (no function in the port, see note) | dead (file is not part of the program).',
		counts: {
			functions: entries.length,
			includes: includes.length,
			ported: all.filter((e) => e.status === 'ported').length,
			todo: all.filter((e) => e.status === 'todo').length,
			absorbed: all.filter((e) => e.status === 'absorbed').length,
			dead: all.filter((e) => e.status === 'dead').length,
			async: all.filter((e) => e.async).length,
			asyncTodo: all.filter((e) => e.async && e.status === 'todo').length
		},
		files: Object.fromEntries(P.files.map((f) => [shortFile(f), { lines: P.lineCounts[f], module: DEAD_FILES[f] || !(f === 'StrandedII.bb' || moduleKinds[f]) ? '' : f === 'StrandedII.bb' ? '$lib/s2/game/main' : `$lib/s2/game/${baseOf(f)}`, kind: DEAD_FILES[f] ? 'dead' : f === 'StrandedII.bb' ? 'own' : (moduleKinds[f] ?? 'declarations') }])),
		functions: all.map(({ calls, ...rest }) => rest)
	};
	write('function_index.json', JSON.stringify(index, null, '\t') + '\n');

	let md = `<!-- ${HEADER.trim().slice(3)} -->\n# Function index\n\nEvery \`Function\` of the original source (${entries.length}) and the top-level code of every included file (${includes.length}, as \`include_<file>()\`).\nImport from \`$lib/s2/game/<file>\` (the module column of function_index.json), always under the original lower-case name.\n\n`;
	md += `| status | count |\n| --- | --- |\n| ported (exists now) | ${index.counts.ported} |\n| todo | ${index.counts.todo} |\n| absorbed (no function in the port) | ${index.counts.absorbed} |\n| dead (file not part of the program) | ${index.counts.dead} |\n| async | ${index.counts.async} (${index.counts.asyncTodo} of them todo) |\n\n`;
	md += `## Async functions\n\nThese return a Promise and must be awaited; everything else is synchronous. See PORTING_GUIDE.md, "Blocking code".\n\n`;
	md += all.filter((e) => e.async).map((e) => `- \`${e.name}\` (${e.file}) - ${e.status === 'ported' ? 'async in the port' : e.asyncBecause}`).join('\n') + '\n\n';
	md += `## Sync barriers\n\nSynchronous in the port although the original reaches a blocking call from them; the blocking part is deferred (PORTING_GUIDE.md).\n\n`;
	md += all.filter((e) => e.barrier).map((e) => `- \`${e.name}\` (${e.file}) - ${e.barrier}`).join('\n') + '\n\n';
	for (const f of P.files) {
		const list = all.filter((e) => e.file === shortFile(f));
		if (!list.length) continue;
		md += `## ${shortFile(f)}\n\n`;
		md += `Module: ${DEAD_FILES[f] ? `none (${DEAD_FILES[f]})` : `\`$lib/s2/game/${baseOf(f)}\``}\n\n`;
		md += `| function | line | lines | sync | status | where / note |\n| --- | --- | --- | --- | --- | --- |\n`;
		for (const e of list) md += `| \`${e.bb === '(top-level code)' ? e.name + '()' : e.bb.replaceAll('|', '\\|')}\` | ${e.line} | ${e.lines} | ${e.async ? 'async' : 'sync'} | ${e.status} | ${[e.via ?? '', e.note ?? '', e.barrier ? 'barrier: ' + e.barrier : ''].filter(Boolean).join('; ').replaceAll('|', '\\|')} |\n`;
		md += '\n';
	}
	write('FUNCTION_INDEX.md', md);
	return { index, moduleKinds };
}

